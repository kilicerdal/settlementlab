"""Run against a fresh local server: python tests/browser_smoke.py."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

output=Path('artifacts')
output.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch()
    context=browser.new_context(viewport={'width':1440,'height':1100})
    context.tracing.start(screenshots=True,snapshots=True,sources=True)
    page=context.new_page()
    try:
        page.goto(os.getenv('SETTLEMENTLAB_URL','http://127.0.0.1:8080'))
        expect(page.get_by_role('heading',name='Confidence starts with the match.')).to_be_visible()
        page.get_by_role('button',name='Run showcase scenario').click()
        expect(page.locator('#detail .badge')).to_have_text('EXCEPTION')
        expect(page.locator('.finding')).to_have_count(2)
        expect(page.locator('.comparison-table .field-break')).to_have_count(2)
        page.evaluate('window.scrollTo(0,0)')
        page.screenshot(path=str(output/'two-sided-exception.png'),full_page=True)
        if os.getenv('SETTLEMENTLAB_TEST_LOCAL_AI') == '1':
            page.get_by_role('button',name='Analyze exception with AI').click()
            expect(page.locator('.ai-report h3')).to_have_text('AI analysis · advisory only',timeout=65000)
            expect(page.locator('.ai-report')).to_contain_text('ollama-local')
            page.screenshot(path=str(output/'local-ai.png'),full_page=True)
        page.get_by_role('button',name='Revise manager submission').click()
        dialog=page.get_by_role('dialog')
        expect(dialog).to_be_visible()
        dialog.get_by_label('Price per share').fill('42.75')
        dialog.get_by_label('Fund allocations').fill('SYN-FUND-ALPHA,6000\nSYN-FUND-BETA,4000')
        dialog.get_by_role('button',name='Submit independent terms').click()
        expect(dialog).not_to_be_visible()
        expect(page.locator('#detail .badge')).to_have_text('MATCHED')
        page.get_by_role('button',name='Affirm instructions').click()
        expect(page.locator('#detail .badge')).to_have_text('AFFIRMED')
        page.get_by_role('button',name='Attempt settlement').click()
        expect(page.locator('#detail .badge')).to_have_text('FAILED')
        page.get_by_role('button',name='Provision demo balances').click()
        expect(page.locator('#detail pre')).to_contain_text('$427,500.00')
        page.get_by_role('button',name='Attempt settlement').click()
        expect(page.locator('#detail .badge')).to_have_text('SETTLED')
        page.get_by_role('button',name='Reconcile statement').click()
        expect(page.get_by_role('status')).to_contain_text('BALANCED')
        page.screenshot(path=str(output/'desktop.png'),full_page=True)
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(output/'mobile.png'),full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        # Exercise manual independent submissions and a real mobile form, not only the seeded demo.
        page.get_by_role('button',name='Submit broker trade').click()
        dialog=page.get_by_role('dialog')
        dialog.get_by_label('Security symbol').fill('LUMA')
        dialog.get_by_label('Quantity',exact=True).fill('25')
        dialog.get_by_label('Price per share').fill('10.25')
        dialog.get_by_label('Trade date',exact=True).fill('2026-11-06')
        dialog.get_by_label('Settlement date').fill('2026-11-09')
        dialog.get_by_role('button',name='Submit independent terms').click()
        expect(dialog).not_to_be_visible()
        expect(page.locator('#detail .badge')).to_have_text('RECEIVED')
        page.get_by_role('button',name='Submit manager terms').click()
        dialog.get_by_label('Security symbol').fill('LUMA')
        dialog.get_by_label('Quantity',exact=True).fill('25')
        dialog.get_by_label('Price per share').fill('10.25')
        dialog.get_by_label('Trade date',exact=True).fill('2026-11-06')
        dialog.get_by_label('Settlement date').fill('2026-11-09')
        dialog.get_by_label('Fund allocations').fill('SYN-FUND-MOBILE,25')
        page.screenshot(path=str(output/'mobile-submission.png'),full_page=False)
        dialog.get_by_role('button',name='Submit independent terms').click()
        expect(dialog).not_to_be_visible()
        expect(page.locator('#detail .badge')).to_have_text('MATCHED')
        page.get_by_label('Search trades').fill('LUMA')
        expect(page.locator('#trades tr')).to_have_count(1)
        expect(page.locator('#trades')).to_contain_text('LUMA')
        page.get_by_label('Lifecycle status').select_option('EXCEPTION')
        expect(page.locator('#trades')).to_contain_text('No trades match your filters.')
        print('Browser journey passed: two-sided breaks → revision → settlement recovery → reconciliation; mobile manual submissions and filters')
    finally:
        context.tracing.stop(path=str(output/'journey.zip'))
        browser.close()
